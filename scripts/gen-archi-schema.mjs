// Turns src/archi/db/schema.prisma into a runtime model descriptor used by the
// in-browser Prisma-compatible store (src/archi/db/client.ts).
// Run: node scripts/gen-archi-schema.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../src/archi/db/schema.prisma", import.meta.url), "utf8");
const scalarTypes = new Set(["String", "Int", "Float", "Boolean", "DateTime", "Json"]);
const enums = new Set([...src.matchAll(/^enum (\w+)/gm)].map((m) => m[1]));
const models = {};

for (const [, name, body] of src.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const fields = {};
  const uniques = [];
  for (const raw of body.split("\n")) {
    const line = raw.replace(/\/\/.*$/, "").trim();
    if (!line || line.startsWith("/**") || line.startsWith("*")) continue;
    const uq = line.match(/^@@unique\(\[([^\]]+)\]\)/);
    if (uq) { uniques.push(uq[1].split(",").map((s) => s.trim())); continue; }
    if (line.startsWith("@@")) continue;
    const m = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
    if (!m) continue;
    const [, fname, ftype, list, optional, attrs] = m;
    const field = { type: ftype, list: Boolean(list), optional: Boolean(optional) };
    if (scalarTypes.has(ftype) || enums.has(ftype)) {
      field.kind = enums.has(ftype) ? "enum" : "scalar";
      if (/@id\b/.test(attrs)) field.id = true;
      if (/@unique\b/.test(attrs)) field.unique = true;
      if (/@updatedAt\b/.test(attrs)) field.updatedAt = true;
      const d = attrs.match(/@default\(((?:[^()]|\([^)]*\))*)\)/);
      if (d) {
        const v = d[1].trim();
        if (v === "cuid()" || v === "uuid()") field.default = { fn: "cuid" };
        else if (v === "now()") field.default = { fn: "now" };
        else if (v === "true" || v === "false") field.default = { value: v === "true" };
        else if (/^-?\d+(\.\d+)?$/.test(v)) field.default = { value: Number(v) };
        else if (/^".*"$/.test(v)) field.default = { value: JSON.parse(v) };
        else field.default = { value: v }; // enum literal
      }
    } else {
      field.kind = "relation";
      const r = attrs.match(/@relation\(([^)]*)\)/);
      if (r) {
        const nameM = r[1].match(/^"([^"]+)"/);
        if (nameM) field.relationName = nameM[1];
        const fieldsM = r[1].match(/fields:\s*\[([^\]]+)\]/);
        const refsM = r[1].match(/references:\s*\[([^\]]+)\]/);
        if (fieldsM) field.fields = fieldsM[1].split(",").map((s) => s.trim());
        if (refsM) field.references = refsM[1].split(",").map((s) => s.trim());
        const del = r[1].match(/onDelete:\s*(\w+)/);
        if (del) field.onDelete = del[1];
      }
    }
    fields[fname] = field;
  }
  models[name] = { fields, uniques };
}

// Resolve back-relations (list / FK-less side) to the FK side.
for (const [name, model] of Object.entries(models)) {
  for (const [fname, field] of Object.entries(model.fields)) {
    if (field.kind !== "relation" || field.fields) continue;
    const target = models[field.type];
    const back = Object.entries(target.fields).find(
      ([, f]) => f.kind === "relation" && f.type === name && f.fields && (f.relationName ?? null) === (field.relationName ?? null),
    );
    if (!back) throw new Error(`No FK side for ${name}.${fname}`);
    field.backFields = back[1].fields;   // FK columns on the target model
    field.backReferences = back[1].references; // referenced columns on this model
  }
}

const delegate = (n) => n[0].toLowerCase() + n.slice(1);
const enumValues = Object.fromEntries(
  [...src.matchAll(/^enum (\w+) \{([\s\S]*?)^\}/gm)].map(([, n, b]) => [
    n,
    b.split("\n").map((l) => l.replace(/\/\/.*$/, "").trim()).filter((l) => /^\w+$/.test(l)),
  ]),
);
const tsScalar = { String: "string", Int: "number", Float: "number", Boolean: "boolean", DateTime: "Date", Json: "any" };
const rowTypes = Object.entries(models).map(([name, model]) => {
  const lines = Object.entries(model.fields).map(([fname, f]) => {
    let t;
    if (f.kind === "scalar") t = tsScalar[f.type];
    else if (f.kind === "enum") t = f.type;
    else t = `${f.type}Row`;
    if (f.list) t = `${t}[]`;
    // Relations are typed as if included so code that reads an include()d relation type-checks.
    const opt = f.optional ? " | null" : "";
    return `  ${fname}: ${t}${opt};`;
  });
  lines.push("  _count: Record<string, number>;");
  return `export interface ${name}Row {\n${lines.join("\n")}\n}\nexport type ${name} = ${name}Row;`;
});
const enumTypes = Object.entries(enumValues).map(
  ([n, vs]) => `export const ${n} = { ${vs.map((v) => `${v}: "${v}"`).join(", ")} } as const;\nexport type ${n} = (typeof ${n})[keyof typeof ${n}];`,
);
const out = `// Generated by scripts/gen-archi-schema.mjs from schema.prisma — do not edit.
export const schema = ${JSON.stringify(models, null, 2)} as const;

export const delegateToModel: Record<string, keyof typeof schema> = ${JSON.stringify(
  Object.fromEntries(Object.keys(models).map((n) => [delegate(n), n])), null, 2)};

${enumTypes.join("\n")}

${rowTypes.join("\n\n")}

export interface ModelRows {
${Object.keys(models).map((n) => `  ${delegate(n)}: ${n}Row;`).join("\n")}
}
`;
writeFileSync(new URL("../src/archi/db/schema.generated.ts", import.meta.url), out);
console.log("models:", Object.keys(models).length);
